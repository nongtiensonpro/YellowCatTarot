export const moonlightSenshiCards: TarotCard[] = tarotCards.map((card, index) => {
  return {
    ...card,
    imagePath: `/Moonlight_Senshi_Tarot/${cleanMoonlightSenshiFilenames[index] || ''}`
  };
});

export function getCardById(id: number): TarotCard | undefined {
  return moonlightSenshiCards.find((card) => card.id === id);
}

export function getCardBySlug(slug: string): TarotCard | undefined {
  return moonlightSenshiCards.find((card) => card.slug === slug);
}
